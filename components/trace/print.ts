import { letterheadDoc, openPrint } from '@/lib/letterhead'
import type { CompanyProfile } from '@/types'

const esc = (s: unknown) => String(s ?? '').replace(/[&<>"']/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]!))
const stamp = (iso: string | null) => iso ? new Date(iso).toLocaleString('en-SG', { day: 'numeric', month: 'short', year: 'numeric', hour: 'numeric', minute: '2-digit' }) : ''

export type ReportSection = { title: string; columns: string[]; rows: (string | number)[][]; empty?: string; note?: string }
/** Label / value boxes instead of a table (form parts, e.g. IBG-F01 "A. Intake"). */
export type FieldSection = { title: string; note?: string; fields: { label: string; value: string | number | null | undefined; wide?: boolean }[] }

/** ☒ chosen ☐ others — how the SOP forms show tick boxes. */
export const ticks = (options: string[], chosen: (string | null | undefined)[] | string | null | undefined) => {
  const set = new Set((Array.isArray(chosen) ? chosen : [chosen]).filter(Boolean).map(x => String(x).toLowerCase()))
  return options.map(o => `${set.has(o.toLowerCase()) ? '☒' : '☐'} ${o}`).join('   ')
}

const section = (s: ReportSection | FieldSection) => {
  const head = `<h2>${esc(s.title)}</h2>${s.note ? `<p class="muted" style="margin:0 0 6px">${esc(s.note)}</p>` : ''}`
  if ('fields' in s) return head + `<div class="fields">${s.fields.map(f => `<div class="box${f.wide ? ' wide' : ''}"><div class="lbl">${esc(f.label)}</div>${esc(f.value === null || f.value === undefined || f.value === '' ? '—' : f.value)}</div>`).join('')}</div>`
  const cols = s.columns
  const rows = s.rows
  return head + `<table><thead><tr>${cols.map(c => `<th>${esc(c)}</th>`).join('')}</tr></thead><tbody>
${rows.length ? rows.map(r => `<tr>${r.map(c => `<td>${esc(c)}</td>`).join('')}</tr>`).join('') : `<tr><td colspan="${cols.length}" class="muted">${esc(s.empty ?? 'None')}</td></tr>`}
</tbody></table>`
}

/** A print-ready traceability / recall report; the browser's "Save as PDF" gives the PDF. */
export function printReport({ company, heading, number, subtitle, facts, sections, signoff, form, landscape }: {
  company: CompanyProfile | null
  heading: string
  number: string
  subtitle: string
  facts: { label: string; value: string }[]
  sections: (ReportSection | FieldSection)[]
  signoff?: { label: string; name: string; when: string | null }[]
  /** Controlled SOP form code, e.g. 'IBG-F01' — printed as the form's document-control line. */
  form?: string
  landscape?: boolean
}) {
  const style = `
  *{box-sizing:border-box} body{font-size:11px}
  h1{font-size:19px;margin:0} h2{font-size:12px;margin:18px 0 6px;text-transform:uppercase;letter-spacing:.05em;color:#334155}
  .muted{color:#64748B} .row{display:flex;justify-content:space-between;gap:24px;align-items:flex-start}
  .facts{display:grid;grid-template-columns:repeat(3,1fr);gap:8px;margin-top:14px}
  .box{border:1px solid #E2E8F0;border-radius:6px;padding:8px} .lbl{font-size:9px;text-transform:uppercase;letter-spacing:.06em;color:#64748B;font-weight:700;margin-bottom:3px}
  table{width:100%;border-collapse:collapse} th{background:#F1F5F9;text-align:left;font-size:9px;text-transform:uppercase;padding:5px 6px}
  td{padding:5px 6px;border-bottom:1px solid #E2E8F0;vertical-align:top}
  .fields{display:grid;grid-template-columns:repeat(3,1fr);gap:6px} .fields .wide{grid-column:1/-1;white-space:pre-wrap}
  .ctl{margin:6px 0 0;font-size:9px;color:#64748B;letter-spacing:.03em}
  .sign{display:flex;gap:12px;margin-top:20px} .sign .box{flex:1;min-height:52px}
  .foot{margin-top:18px;font-size:9px;color:#64748B;border-top:1px solid #E2E8F0;padding-top:6px}
  tr,.box{page-break-inside:avoid}
`
  const body = `<div class="row">
  <div></div>
  <div style="text-align:right"><h1>${esc(heading.toUpperCase())}</h1><div style="font-size:14px;font-weight:700;font-family:ui-monospace,Menlo,monospace">${esc(number)}</div><div class="muted">${esc(subtitle)}</div></div>
</div>
${form ? `<div class="ctl">Form ${esc(form)} · Rev 00 · Refer to IBG-QMS-SOP-008 · Generated by the I-BG IMS from live records</div>` : ''}
<div class="facts">${facts.map(f => `<div class="box"><div class="lbl">${esc(f.label)}</div>${esc(f.value)}</div>`).join('')}</div>
${sections.map(section).join('')}
${signoff?.length ? `<div class="sign">${signoff.map(x => `<div class="box"><div class="lbl">${esc(x.label)}</div><b>${esc(x.name)}</b><div class="muted">${esc(stamp(x.when))}</div></div>`).join('')}</div>` : ''}
<div class="foot">This is a computer-generated document. No signature or company chop is required. ${esc(number)} · printed ${esc(stamp(new Date().toISOString()))}</div>
`
  openPrint(letterheadDoc({ title: `${number} — ${heading}`, company, style, body, landscape }))
}
